/**
 * Checks that the app is really installable — and the rest.
 *
 * ## Why a script rather than a Vitest test
 * This check reads FILES: the manifest and the PNGs of `public/`, whose
 * dimensions it re-reads in the header. The tests of this repository live in
 * `src`, where the typing deliberately does not expose the Node modules -
 * opening `node:fs` to `src` for a single test would mostly allow importing
 * them by accident in browser code. Same choice as `check-contrast.mjs`, and
 * the same lack of dependency.
 *
 * ## What it catches
 * A failed installation produces **no message**: the browser simply removes
 * the prompt. A declared but missing icon, a size that does not match its
 * file, a `display` fallen back to `browser`, and the app stops being
 * installable without a single screen changing its look.
 *
 * Since the manifest and the icons are generated by `make-icons.mjs`, this
 * script checks the agreement between what is PROMISED and what is really on
 * the disk - this is the only place where the promise can come apart from
 * the file.
 *
 * Usage: `npm run check:pwa`
 */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const racine = join(dirname(fileURLToPath(import.meta.url)), '..', 'public')
const problemes = []

function verifier(condition, message) {
  if (!condition) problemes.push(message)
}

let manifeste
try {
  manifeste = JSON.parse(readFileSync(join(racine, 'manifest.webmanifest'), 'utf8'))
} catch (cause) {
  console.error(`manifest.webmanifest unreadable: ${cause.message}`)
  console.error('Run `npm run icons` to regenerate it.')
  process.exit(1)
}

// --- What a browser requires before offering the installation
verifier(typeof manifeste.name === 'string' && manifeste.name.length > 0, 'name missing')
verifier(typeof manifeste.short_name === 'string' && manifeste.short_name.length > 0, 'short_name missing')
// Relative, because the app lives at the root in dev and under /core/ in the
// Docker image: an absolute start_url would open the home page of the site.
verifier(manifeste.start_url === './', `start_url must be "./" (read: ${manifeste.start_url})`)
verifier(
  ['standalone', 'fullscreen', 'minimal-ui'].includes(manifeste.display),
  `display "${manifeste.display}" does not make the app installable`,
)
// Set by the system before the first byte of CSS.
verifier(/^#[0-9a-f]{6}$/i.test(manifeste.background_color ?? ''), 'background_color missing or malformed')
verifier(/^#[0-9a-f]{6}$/i.test(manifeste.theme_color ?? ''), 'theme_color missing or malformed')
verifier(manifeste.lang === 'fr', 'lang must be "fr" - the app is entirely in French')

// --- Do the promised icons exist, at the announced size?
const icones = Array.isArray(manifeste.icons) ? manifeste.icons : []
verifier(icones.length > 0, 'no icon declared')

for (const icone of icones) {
  const chemin = join(racine, icone.src.replace(/^\//, ''))
  let octets
  try {
    octets = readFileSync(chemin)
  } catch {
    problemes.push(`${icone.src} is declared in the manifest but missing from public/`)
    continue
  }
  if (octets.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') {
    problemes.push(`${icone.src} is not a PNG`)
    continue
  }
  // Dimensions re-read in the IHDR header, never deduced from the file name.
  const reelles = `${octets.readUInt32BE(16)}x${octets.readUInt32BE(20)}`
  verifier(reelles === icone.sizes, `${icone.src} announces ${icone.sizes} and measures ${reelles}`)
}

const tailles = icones.map((i) => i.sizes)
verifier(tailles.includes('192x192'), '192x192 icon missing (required for installation)')
verifier(tailles.includes('512x512'), '512x512 icon missing (required for installation)')
// A maskable alone would be cropped everywhere; an "any" alone would float in
// an Android launcher circle. Both are needed.
verifier(
  icones.some((i) => i.purpose === 'maskable'),
  'no "maskable" icon: Android launchers will crop the drawing',
)
verifier(
  icones.some((i) => i.purpose === 'any'),
  'no "any" icon: a maskable alone would be cropped everywhere',
)

// --- The service worker, without which no installation prompt appears
try {
  const sw = readFileSync(join(racine, 'sw.js'), 'utf8')
  verifier(/addEventListener\(\s*'fetch'/.test(sw), 'sw.js does not listen to `fetch`: no installation prompt')
} catch {
  problemes.push('sw.js missing from public/')
}

if (problemes.length > 0) {
  console.error(`Installability: ${problemes.length} problem(s).`)
  for (const probleme of problemes) console.error(`  - ${probleme}`)
  process.exit(1)
}

console.log(
  `Installability: valid manifest, ${icones.length} icons present and at the announced dimensions, service worker in place.`,
)
